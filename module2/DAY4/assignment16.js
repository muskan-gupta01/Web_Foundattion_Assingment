// Grade Calculator

let name = "Muskan";
let marks = 85;

console.log("Student Name:", name);
console.log("Marks:", marks);

if (marks >= 90) {
    console.log("Grade: A+");
}
else if (marks >= 80) {
    console.log("Grade: A");
}
else if (marks >= 70) {
    console.log("Grade: B");
}
else if (marks >= 60) {
    console.log("Grade: C");
}
else if (marks >= 40) {
    console.log("Grade: D");
}
else if (marks >= 0) {
    console.log("Grade: Fail");
}
else {
    console.log("Invalid Marks");
}
